#!/usr/bin/env bash

set -e

# Resolve all requirements (main, test, and docs) into one lock file that installs on every
# supported Python version. --universal adds environment markers where versions must differ,
# and --python-version pins the floor to the oldest version in the CI test matrix.
LOCK_BODY=$(uv pip compile requirements.txt requirements-test.txt requirements-docs.txt \
    --universal \
    --python-version 3.10 \
    --no-annotate \
    --no-header)

printf "# THIS IS AN AUTOGENERATED LOCKFILE. DO NOT EDIT MANUALLY.\n%s\n" "${LOCK_BODY}" > requirements.lock

echo "Rebuild containers to verify there are no conflicts."
